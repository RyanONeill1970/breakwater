namespace Breakwater;

/// <summary>The kinds of jungle tree <see cref="Flora"/> can grow.</summary>
public enum TreeShape
{
    /// <summary>A mid-height tree with a round, lumpy crown.</summary>
    Broadleaf,

    /// <summary>A tall rainforest tree whose flat crown spreads above the rest.</summary>
    Emergent,

    /// <summary>Undergrowth: a low bush with no visible trunk.</summary>
    Shrub,
}
